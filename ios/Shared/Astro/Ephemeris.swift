import Foundation

public enum Body: Int, CaseIterable, Codable, Hashable, Sendable {
    case sun, moon, mercury, venus, mars, jupiter, saturn, uranus, neptune, pluto, node

    public var name: String {
        switch self {
        case .sun: "Sun"; case .moon: "Moon"; case .mercury: "Mercury"; case .venus: "Venus"
        case .mars: "Mars"; case .jupiter: "Jupiter"; case .saturn: "Saturn"; case .uranus: "Uranus"
        case .neptune: "Neptune"; case .pluto: "Pluto"; case .node: "North Node"
        }
    }
    /// Text-presentation glyph (U+FE0E keeps it monochrome).
    public var glyph: String {
        switch self {
        case .sun: "☉"; case .moon: "☽"; case .mercury: "☿\u{FE0E}"; case .venus: "♀\u{FE0E}"
        case .mars: "♂\u{FE0E}"; case .jupiter: "♃\u{FE0E}"; case .saturn: "♄\u{FE0E}"
        case .uranus: "♅\u{FE0E}"; case .neptune: "♆\u{FE0E}"; case .pluto: "♇\u{FE0E}"; case .node: "☊"
        }
    }
    public static let planets: [Body] = [.sun, .moon, .mercury, .venus, .mars, .jupiter, .saturn, .uranus, .neptune, .pluto]
    public static let slow: [Body] = [.jupiter, .saturn, .uranus, .neptune, .pluto]
}

public enum Zodiac {
    public static let names = ["Aries", "Taurus", "Gemini", "Cancer", "Leo", "Virgo", "Libra", "Scorpio", "Sagittarius", "Capricorn", "Aquarius", "Pisces"]
    public static let glyphs = ["♈\u{FE0E}", "♉\u{FE0E}", "♊\u{FE0E}", "♋\u{FE0E}", "♌\u{FE0E}", "♍\u{FE0E}", "♎\u{FE0E}", "♏\u{FE0E}", "♐\u{FE0E}", "♑\u{FE0E}", "♒\u{FE0E}", "♓\u{FE0E}"]
    public static func index(_ lon: Double) -> Int { Int((norm(lon) / 30).rounded(.down)) % 12 }
    public static func name(_ lon: Double) -> String { names[index(lon)] }
    public static func glyph(_ lon: Double) -> String { glyphs[index(lon)] }
    public static func degree(_ lon: Double) -> Int { Int(norm(lon).truncatingRemainder(dividingBy: 30)) }
    public static func label(_ lon: Double) -> String { "\(degree(lon))° \(name(lon))" }
    public static func shortLabel(_ lon: Double) -> String { "\(degree(lon))°\(String(name(lon).prefix(3)))" }
}

@inline(__always) public func norm(_ a: Double) -> Double {
    let r = a.truncatingRemainder(dividingBy: 360)
    return r < 0 ? r + 360 : r
}
/// Signed difference a-b in (-180, 180].
@inline(__always) public func angDiff(_ a: Double, _ b: Double) -> Double {
    var d = norm(a - b)
    if d > 180 { d -= 360 }
    return d
}

public enum JD {
    public static func from(_ date: Date) -> Double { date.timeIntervalSince1970 / 86400.0 + 2440587.5 }
    public static func date(_ jd: Double) -> Date { Date(timeIntervalSince1970: (jd - 2440587.5) * 86400.0) }
}

/// Daily samples of ecliptic position 1900–2100 (generated by scripts/ios/gen_ephemeris.py from Swiss Ephemeris),
/// interpolated with a 4-point Lagrange cubic. Max error is ~0.0015° (Moon), i.e. a few arcseconds.
public final class Ephemeris: @unchecked Sendable {
    public static let shared = Ephemeris()
    private let lon: [[Int32]]
    private let lat: [[Int16]]
    private let days: Int
    private let jdStart: Double   // JD at 00:00 UT of the first sample

    public var coversFrom: Date { JD.date(jdStart + 2) }
    public var coversTo: Date { JD.date(jdStart + Double(days) - 3) }

    private init() {
        guard let url = Bundle(for: BundleToken.self).url(forResource: "ephemeris", withExtension: "bin"),
              let data = try? Data(contentsOf: url, options: .mappedIfSafe), data.count > 16 else {
            fatalError("ephemeris.bin missing from AstroKit bundle")
        }
        let startInt: Int32 = data.withUnsafeBytes { $0.loadUnaligned(fromByteOffset: 4, as: Int32.self) }
        let n = Int(data.withUnsafeBytes { $0.loadUnaligned(fromByteOffset: 8, as: UInt32.self) })
        let nb = Int(data.withUnsafeBytes { $0.loadUnaligned(fromByteOffset: 12, as: UInt32.self) })
        days = n
        jdStart = Double(startInt) - 0.5
        var off = 16
        func block<T>(_ type: T.Type, count: Int) -> [T] {
            let bytes = count * MemoryLayout<T>.stride
            let arr = [T](unsafeUninitializedCapacity: count) { buf, n in
                data.withUnsafeBytes { raw in _ = memcpy(buf.baseAddress!, raw.baseAddress!.advanced(by: off), bytes) }
                n = count
            }
            off += bytes
            return arr
        }
        var lons: [[Int32]] = [], lats: [[Int16]] = []
        for _ in 0..<nb { lons.append(block(Int32.self, count: n)) }
        for _ in 0..<nb { lats.append(block(Int16.self, count: n)) }
        lon = lons; lat = lats
    }

    private func weights(_ f: Double) -> (Double, Double, Double, Double) {
        (-f * (f - 1) * (f - 2) / 6, (f + 1) * (f - 1) * (f - 2) / 2, -(f + 1) * f * (f - 2) / 2, (f + 1) * f * (f - 1) / 6)
    }
    private func locate(_ jd: Double) -> (Int, Double) {
        let t = max(1.0, min(Double(days - 3), jd - jdStart))
        let k = Int(t.rounded(.down))
        return (k, t - Double(k))
    }

    /// Ecliptic longitude in degrees [0, 360).
    public func longitude(_ b: Body, jd: Double) -> Double {
        let (k, f) = locate(jd)
        let s = lon[b.rawValue]
        let base = Double(s[k]) / 1e4
        func u(_ i: Int) -> Double { base + angDiff(Double(s[i]) / 1e4, base) }
        let w = weights(f)
        return norm(u(k - 1) * w.0 + base * w.1 + u(k + 1) * w.2 + u(k + 2) * w.3)
    }
    public func latitude(_ b: Body, jd: Double) -> Double {
        let (k, f) = locate(jd)
        let s = lat[b.rawValue]; let w = weights(f)
        return (Double(s[k - 1]) * w.0 + Double(s[k]) * w.1 + Double(s[k + 1]) * w.2 + Double(s[k + 2]) * w.3) / 1e3
    }
    /// Degrees per day (negative = retrograde).
    public func speed(_ b: Body, jd: Double) -> Double {
        angDiff(longitude(b, jd: jd + 0.05), longitude(b, jd: jd - 0.05)) / 0.1
    }
    public func longitude(_ b: Body, date: Date) -> Double { longitude(b, jd: JD.from(date)) }
    public func isRetrograde(_ b: Body, date: Date) -> Bool { speed(b, jd: JD.from(date)) < 0 }
}

private final class BundleToken {}
